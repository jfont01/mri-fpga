    local module_dir="$1"

    mkdir -p "$module_dir/build"

    mkdir -p "$module_dir/cpp"
    mkdir -p "$module_dir/flist"
    mkdir -p "$module_dir/rtl"
    mkdir -p "$module_dir/testbench"
