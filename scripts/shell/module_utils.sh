write_cpp_cpp_template() {
    local module_name="$1"
    local module_dir="$2"

    write_file_if_empty "$module_dir/cpp/${module_name}.cpp" <<EOF
#include "${module_name}.hpp"

namespace ${module_name} {

void ${module_name}_model::connect_clocks(rtl::ClockDomain& clk)
{
    (void)clk;

    /*
     * Add sequential state/registers to the clock domain.
     *
     * Example:
     *
     * clk.add(valid_r);
     * clk.add(y_r);
     */
}

void ${module_name}_model::init()
{
    /*
     * Initialize ports, wires and registers.
     *
     * Example:
     *
     * i_en   = false;
     * i_word = in_t {};
     *
     * o_en   = false;
     * o_word = out_t {};
     *
     * y_w = out_t {};
     *
     * valid_r.set_initial_value(false);
     * y_r.set_initial_value(out_t {});
     */
}

void ${module_name}_model::combinational()
{
    /*
     * Describe combinational behavior.
     *
     * Example:
     *
     * y_w = out_t(i_word.value());
     *
     * o_en   = valid_r.o;
     * o_word = y_r.o;
     */
}

void ${module_name}_model::sequential()
{
    /*
     * Describe clocked behavior.
     *
     * Important:
     * - Assign next register values using reg.i
     * - Read current register values using reg.o
     *
     * Example:
     *
     * valid_r.i = i_en.value();
     *
     * if (i_en.value()) {
     *     y_r.i = y_w.value();
     * }
     * else {
     *     y_r.i = y_r.o;
     * }
     */
}

} // namespace ${module_name}
EOF
}
write_cpp_hpp_template() {
    local module_name="$1"
    local module_dir="$2"
    local prefix

    prefix="$(module_prefix "$module_name")"

    write_file_if_empty "$module_dir/cpp/${module_name}.hpp" <<EOF
#pragma once

#include "rtlsim.hpp"

#include <ap_fixed.h>
#include <cstdint>

namespace ${module_name} {

/*
 * --------------------------------------------------------------------------
 * Parameters
 * --------------------------------------------------------------------------
 *
 * These values are equivalent to Verilog parameters.
 * They may be overridden from the build system using compiler defines.
 *
 * Example:
 *
 * #ifndef ${prefix}_NB_IN
 * #define ${prefix}_NB_IN 16
 * #endif
 *
 * #ifndef ${prefix}_NBF_IN
 * #define ${prefix}_NBF_IN 14
 * #endif
 *
 * #ifndef ${prefix}_NB_OUT
 * #define ${prefix}_NB_OUT 16
 * #endif
 *
 * #ifndef ${prefix}_NBF_OUT
 * #define ${prefix}_NBF_OUT 14
 * #endif
 */

enum parameters : int {
    /*
     * Example:
     *
     * NB_IN   = ${prefix}_NB_IN,
     * NBF_IN  = ${prefix}_NBF_IN,
     * NB_OUT  = ${prefix}_NB_OUT,
     * NBF_OUT = ${prefix}_NBF_OUT
     */
};

/*
 * --------------------------------------------------------------------------
 * Localparameters
 * --------------------------------------------------------------------------
 *
 * These values are equivalent to Verilog localparams.
 * They are derived from parameters and must not be overridden externally.
 */

enum localparameters : int {
    /*
     * Example:
     *
     * NBI_IN  = NB_IN  - NBF_IN,
     * NBI_OUT = NB_OUT - NBF_OUT
     */
};

/*
 * --------------------------------------------------------------------------
 * Data types
 * --------------------------------------------------------------------------
 *
 * ap_fixed standard convention:
 *   ap_fixed<W, I>
 *   W = total width
 *   I = integer bits, sign included
 *
 * Example:
 *
 * using bit_t = bool;
 * using in_t  = ap_fixed<NB_IN,  NBI_IN>;
 * using out_t = ap_fixed<NB_OUT, NBI_OUT>;
 */

class ${module_name}_model final : public rtl::Module {
public:
    ${module_name}_model() = default;

    /*
     * ----------------------------------------------------------------------
     * Ports
     * ----------------------------------------------------------------------
     *
     * Example:
     *
     * rtl::InPort<bit_t> i_en;
     * rtl::InPort<in_t>  i_word;
     *
     * rtl::OutPort<bit_t> o_en;
     * rtl::OutPort<out_t> o_word;
     */

    /*
     * ----------------------------------------------------------------------
     * Internal wires/registers
     * ----------------------------------------------------------------------
     *
     * Example:
     *
     * rtl::Wire<out_t> y_w;
     *
     * rtl::Reg<bit_t> valid_r;
     * rtl::Reg<out_t> y_r;
     */

    void connect_clocks(rtl::ClockDomain& clk) override;
    void init() override;
    void combinational() override;
    void sequential() override;

private:

};

} // namespace ${module_name}
EOF
}


create_module_files() {
    local module_name="$1"
    local module_dir="$2"

    # C++ model
    write_cpp_hpp_template "$module_name" "$module_dir"
    write_cpp_cpp_template "$module_name" "$module_dir"

    # RTL
    write_rtl_template "$module_name" "$module_dir"

    # Testbench
    write_tb_hpp_template "$module_name" "$module_dir"
    write_tb_cpp_template "$module_name" "$module_dir"
    write_tb_sv_template "$module_name" "$module_dir"

    write_default_sim_regression_json \
        "$module_dir/testbench/${module_name}_tb_regression.json"

    # Synthesis
    write_synth_wrapper_template "$module_name" "$module_dir"
    write_default_synth_regression_json \
        "$module_dir/synthesis/${module_name}_synth_regression.json"

    # Implementation
    write_impl_wrapper_template "$module_name" "$module_dir"
    write_default_impl_regression_json \
        "$module_dir/implementation/${module_name}_impl_regression.json"

    # Flists
    touch "$module_dir/flist/${module_name}_tb.flist"
    touch "$module_dir/flist/${module_name}_synth.flist"
    touch "$module_dir/flist/${module_name}_impl.flist"
}

create_module() {
    local module_name="${1:-}"

    module_utils_require_env MODULES_ROOT || return 1
    validate_module_name "$module_name" || return 1

    local prefix
    prefix="$(module_prefix "$module_name")"

    local module_dir="$MODULES_ROOT/$module_name"
    local variables_file="$module_dir/${module_name}_vars.sh"

    create_module_dirs "$module_dir"

    if [[ ! -f "$variables_file" ]]; then
        write_module_vars_file "$module_name" "$prefix" "$variables_file"
        module_utils_log "created vars file: $variables_file"
    else
        module_utils_log "vars file already exists: $variables_file"
    fi

    create_module_files "$module_name" "$module_dir"

    source "$variables_file"

    module_utils_log "module created: $module_dir"
}

refresh_module_vars() {
    local module_name="${1:-}"

    module_utils_require_env MODULES_ROOT || return 1
    validate_module_name "$module_name" || return 1

    local prefix
    prefix="$(module_prefix "$module_name")"

    local module_dir="$MODULES_ROOT/$module_name"
    local variables_file="$module_dir/${module_name}_vars.sh"

    if [[ ! -d "$module_dir" ]]; then
        module_utils_error "module does not exist: $module_dir"
        return 1
    fi

    write_module_vars_file "$module_name" "$prefix" "$variables_file"
    source "$variables_file"

    module_utils_log "refreshed vars file: $variables_file"
}

cd_module() {
    local module_name="${1:-}"

    module_utils_require_env MODULES_ROOT || return 1

    if [[ -z "$module_name" ]]; then
        module_utils_error "usage: cd_module <module_name>"
        return 1
    fi

    if [[ ! -d "$MODULES_ROOT/$module_name" ]]; then
        module_utils_error "module does not exist: $MODULES_ROOT/$module_name"
        return 1
    fi

    cd "$MODULES_ROOT/$module_name" || return 1
}

list_modules() {
    module_utils_require_env MODULES_ROOT || return 1

    find "$MODULES_ROOT" \
        -mindepth 1 \
        -maxdepth 1 \
        -type d \
        -printf "%f\n" 2>/dev/null | sort
}