# This file is autogenerated by create_module / refresh_module_vars.

export ${prefix}_DIR="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
export ${prefix}_VARS_SH="\$${prefix}_DIR/${module_name}_vars.sh"

# Build directories
export ${prefix}_BUILD_DIR="\$${prefix}_DIR/build"
export ${prefix}_SIM_BUILD_DIR="\$${prefix}_BUILD_DIR/simulation"
export ${prefix}_SYNTH_BUILD_DIR="\$${prefix}_BUILD_DIR/synthesis"
export ${prefix}_IMPL_BUILD_DIR="\$${prefix}_BUILD_DIR/implementation"

# Source directories
export ${prefix}_CPP_DIR="\$${prefix}_DIR/cpp"
export ${prefix}_FLIST_DIR="\$${prefix}_DIR/flist"
export ${prefix}_RTL_DIR="\$${prefix}_DIR/rtl"
export ${prefix}_TB_DIR="\$${prefix}_DIR/testbench"
export ${prefix}_SYNTH_DIR="\$${prefix}_DIR/synthesis"
export ${prefix}_IMPL_DIR="\$${prefix}_DIR/implementation"

# C++ model files
export ${prefix}_CPP_HPP="\$${prefix}_CPP_DIR/${module_name}.hpp"
export ${prefix}_CPP_CPP="\$${prefix}_CPP_DIR/${module_name}.cpp"

# RTL files
export ${prefix}_V="\$${prefix}_RTL_DIR/${module_name}.v"

# Testbench files
