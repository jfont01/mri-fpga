#!/usr/bin/env bash

# Este archivo debe ser sourced desde set_env.sh.

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    echo "[module_utils.sh] ERROR: this file must be sourced, not executed." >&2
    exit 1
fi

module_utils_log() {
    echo "[module_utils.sh] $*"
}

module_utils_error() {
    echo "[module_utils.sh] ERROR: $*" >&2
}

module_utils_require_env() {
    local name="$1"

    if [[ -z "${!name:-}" ]]; then
        module_utils_error "environment variable not defined: $name"
        return 1
    fi
}

module_prefix() {
    local name="$1"
    echo "$name" | tr '[:lower:]' '[:upper:]'
}

validate_module_name() {
    local module_name="$1"

    if [[ -z "$module_name" ]]; then
        module_utils_error "usage: create_module <module_name>"
        return 1
    fi

    if [[ ! "$module_name" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]]; then
        module_utils_error "invalid module name: $module_name"
        return 1
    fi
}

source_module_vars() {
    module_utils_require_env MODULES_ROOT || return 1

    local vars_file

    shopt -s nullglob
    for vars_file in "$MODULES_ROOT"/*/*_vars.sh; do
        source "$vars_file"
    done
    shopt -u nullglob
}

write_module_vars_file() {
    local module_name="$1"
    local prefix="$2"
    local variables_file="$3"

    cat > "$variables_file" <<EOF
